          </p>
          <p class="card-text">
            同時，明代殿試中得高第者並不立即授官，而是安排進入翰林院學習。這一舉措，雖讓舉士得以了解具體政務，增長學問，為日後擔任高官打下基礎，但也將最優秀的人才束縛在中央的象牙塔中，遠離了地方治理的實踐。這種「重理論、輕實踐」的授官模式，使得明代官員隊伍整體缺乏處理複雜社會問題的能力，最終在明末的內憂外患中不堪一擊。
          </p>
