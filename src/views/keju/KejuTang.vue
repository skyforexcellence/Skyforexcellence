      <li><strong>應試資格：</strong>無嚴格規限，無官職的普通士人、已有官職的在職官員均可報考。</li>
      <li><strong>授官待遇：</strong>制科登科者待遇遠高於常科：在職官員可直接升遷，白身士子可直接授予官職，無需再經過吏部銓選。</li>
