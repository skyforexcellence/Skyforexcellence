        </ul>
      </li>
    </ul>

    <h2 class="subsection-title">
      三、井田制的基本運作
    </h2>
    <p class="section-text">
      井田制以「井」字為基礎，形成九宮格狀的土地分配模式：
    </p>
    <ul class="section-list">
      <li>
        <span class="highlight">井田的結構</span>：
        <ul>
          <li>一個「井田」分成<span class="highlight">九塊土地</span>，每，每塊約100畝</li>
          <li>中央為<span class="highlight">公田</span>，收成歸國家或貴族</li>
          <li>四周八塊為<span class="highlight">私田</span>，分配給八家農民</li>
          <li>八家農民共同耕種公田，各自耕種私田</li>
        </ul>
      </li>
      <li>
        <span class="highlight">公田制度</span>：
        <ul>
          <li>公田由八家農民共同耕作</li>
          <li>收成全部歸國家或貴族</li>
          <li>相當於稅收，是田賦的早期形式</li>
          <li>農民無法分享公田收成</li>
        </ul>
      </li>
      <li>
        <span class="highlight">私田制度</span>：
        <ul>
          <li>私田由農民分戶耕種</li>
          <li>收成大部分留給自己</li>
          <li>部分繳納貢賦給貴族</li>
          <li>私田不得自由買賣</li>
        </ul>
      </li>
      <li>
        <span class="highlight">農民義務</span>：
        <ul>
          <li>耕種公田：定期集體勞動</li>
          <li>耕種私田：維持家庭生計</li>
          <li>提供兵役：戰時從軍作戰</li>
          <li>提供勞役：修築工程、運輸物資</li>
        </ul>
      </li>
    </ul>

