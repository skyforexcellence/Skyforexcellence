    <h2 class="subsection-title">
      六、井田制瓦解的原因
    </h2>
    <h3 class="section-title">（一）政治因素</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">諸侯勢力增強</span>：
        <ul>
          <li>春秋時期，諸侯國勢力日增</li>
          <li>周王室衰微，無力控制諸侯</li>
          <li>諸侯不再按傳統模式接受土地分配</li>
          <li>卿大夫勢力也隨之壯大</li>
        </ul>
      </li>
      <li>
        <span class="highlight">戰國競爭</span>：
        <ul>
          <li>戰國時期，各國為了增強國力</li>
          <li>推行變法，鼓勵開墾私田</li>
          <li>土地兼併合法化</li>
          <li>井田制名存實亡</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（二）經濟因素</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">鐵器與牛耕普及</span>：
        <ul>
          <li>春秋戰國時期，鐵器逐漸普及</li>
          <li>牛耕技術廣泛應用</li>
          <li>農業生產力大幅提升</li>
          <li>更有利於小農私有土地的發展</li>
        </ul>
      </li>
      <li>
        <span class="highlight">私田開墾增加</span>：
        <ul>
          <li>農民利用鐵器、牛耕開墾荒地</li>
          <li>私田數量不斷增加</li>
          <li>私田收成不須繳納給貴族</li>
          <li>鼓勵農民開墾更多土地</li>
        </ul>
      </li>
      <li>
        <span class="highlight">商品經濟發展</span>：
        <ul>
          <li>商品交換逐漸活躍</li>
          <li>土地開始成為商品</li>
          <li>貴族、商人購買土地</li>
          <li>土地買賣成為現實</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（三）社會因素</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">農民意識覺醒</span>：
        <ul>
          <li>農民意識到私田的好處</li>
          <li>更願意耕種私田而非公田</li>
          <li>公田耕作積極性下降</li>
          <li>部分農民逃亡，開墾私田</li>
        </ul>
      </li>
      <li>
        <span class="highlight">階層變動</span>：
        <ul>
          <li>商人、地主階層興起</li>
          <li>新興地主購買土地</li>
          <li>舊有貴族勢力受到挑戰</li>
          <li>社會結構發生變化</li>
        </ul>
      </li>
    </ul>

