            <p>到了德宗時期，宰相楊炎推行兩稅法，正式廢除了按丁口授田徵稅的規則，改為按土地、財產徵稅，這等於在法律上承認了土地私有的合法性，沿用三百年的均田制，就此徹底退出了歷史舞台。</p>
