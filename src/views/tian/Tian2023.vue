        <p>北魏太和九年（485年）孝文帝頒行的均田制，從來不是一紙簡單的土地分配條文，而是一套針對五胡亂華後北方社會全面崩壞的系統性治理方案。資料一中的每項制度設計，都緊扣著「安民、限豪、裕國」的三重核心目標，其背後的邏輯與實際成效，可從三個維度完整闡釋。</p>
