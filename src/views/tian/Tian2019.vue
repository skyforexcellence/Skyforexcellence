              <p>總而言之，均田制的敗壞，是唐朝由盛轉衰的轉折點。它的崩潰，讓唐朝賴以維持統治的財政、軍事制度全盤失效，最終導致社會動盪、中央衰弱、藩鎮割據，曾經盛極一時的大唐王朝，也一步步走向了衰落與滅亡。</p>
