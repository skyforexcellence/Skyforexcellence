              <p>均田制的敗壞，首先直接摧毀了唐朝的財政根基。建立在均田制之上的租庸調制，隨著均田制的崩潰完全無法推行：大量土地被豪強兼併，可豪強貴族有免稅的特權，根本不用向國家交稅；失去土地的農民要麼逃亡，要麼成為地主的佃戶，國家也無法向他們收稅。安史之亂後，全國納稅戶口從開元年間的九百多萬戶，驟降到三百多萬戶，政府能控制的納稅人口不到原來的三分之一，國家財政直接瀕臨崩潰。為了彌補財政缺口，朝廷只能不斷加稅，巧立名目向百姓苛捐雜稅，百姓的負擔越來越重，只能繼續逃亡，形成了「加稅→逃亡→再加稅」的惡性循環。這不僅讓國家的財政越來越困難，更引發了大量的民變，社會動盪不安，唐朝的統治根基被嚴重動搖。</p>

