        <ul>
          <li>戰亂與逃亡導致大量戶口冊與田籍散失</li>
          <li>安史之亂後，戶口從約2000萬減少至約800萬</li>
          <li>出現「有戶無田」與「有田無戶」的情況</li>
          <li>國家難以依冊分田與徵稅</li>
        </ul>
      </li>
      <li>
        <span class="highlight">戶籍失修</span>：
        <ul>
          <li>戶籍與田籍多年不修</li>
          <li>登記與實際不符</li>
          <li>地方官吏缺乏動力更新戶籍</li>
          <li>均田制失去基礎</li>
        </ul>
      </li>
    </ul>

