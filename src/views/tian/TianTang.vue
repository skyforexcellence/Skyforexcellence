          <li>大量土地不再按均田規例運作</li>
        </ul>
      </li>
      <li>
        <span class="highlight">寺院莊園</span>：
        <ul>
          <li>寺院利用宗教特權兼併土地</li>
          <li>獲得大量莊田</li>
          <li>寺院經濟興起</li>
          <li>與貴族莊園競爭</li>
        </ul>
      </li>
      <li>
        <span class="highlight">莊園特點</span>：
        <ul>
