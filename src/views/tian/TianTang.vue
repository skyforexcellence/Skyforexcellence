    <h2 class="subsection-title">
      六、兩稅法的出現︰由「分田」到「以稅為主」
    </h2>
    <h3 class="section-title">（一）兩稅法的背景</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">財政困難</span>：
        <ul>
          <li>安史之亂後，唐德宗時期面臨財政困難</li>
          <li>租庸調制度已無法實行</li>
          <li>國家收入大幅減少</li>
          <li>軍費開支龐大</li>
        </ul>
      </li>
      <li>
        <span class="highlight">楊炎建議</span>：
        <ul>
          <li>楊炎提出兩稅法改革</li>
          <li>得到唐德宗支持</li>
          <li>於780年正式推行</li>
          <li>成為唐代後期主要稅制</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（二）兩稅法的內容</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">徵收時間</span>：
        <ul>
          <li>夏、秋兩次徵稅</li>
          <li>夏稅：6月，繳納小麥、絹布</li>
          <li>秋稅：11月，繳納粟米、布帛</li>
          <li>分兩次徵收，減輕農民負擔</li>
        </ul>
      </li>
      <li>
        <span class="highlight">徵稅基礎</span>：
        <ul>
          <li>以戶口實際占有的土地與財產為基礎</li>
          <li>不再完全依均田冊</li>
          <li>承認土地集中與私有現實</li>
          <li>按實際情況徵稅</li>
        </ul>
      </li>
      <li>
        <span class="highlight">稅額計算</span>：
        <ul>
          <li>按土地面積與等級徵稅</li>
          <li>按財產多少徵稅</li>
          <li>取消戶稅，改以田賦為主</li>
          <li>更符合實際經濟情況</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（三）兩稅法的特點</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">承認土地私有</span>：
        <ul>
          <li>國家承認土地集中與私有現實</li>
          <li>田制重點由平均分田轉為合理徵稅與調整賦負</li>
          <li>地主經濟合法化</li>
          <li>影響宋以後田制格局</li>
        </ul>
      </li>
      <li>
        <span class="highlight">簡化稅制</span>：
        <ul>
          <li>廢除租庸調，簡化稅制</li>
          <li>分兩次徵收，清晰明確</li>
          <li>減少繁瑣的徵稅程序</li>
          <li>提高行政效率</li>
        </ul>
      </li>
      <li>
        <span class="highlight">擴大稅基</span>：
        <ul>
          <li>按實際土地與財產徵稅</li>
          <li>擴大稅基，增加收入</li>
          <li>減少逃稅空間</li>
          <li>改善國家財政</li>
        </ul>
      </li>
    </ul>

