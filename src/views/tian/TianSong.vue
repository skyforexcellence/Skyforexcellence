    <h2 class="subsection-title">
      八、宋代田制的特點與影響
    </h2>
    <h3 class="section-title">（一）宋代田制的特點</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">土地高度私有化</span>：
        <ul>
          <li>土地所有權高度集中</li>
          <li>地主擁有大量土地</li>
          <li>土地買賣自由</li>
          <li>成為重要的財富形式</li>
        </ul>
      </li>
      <li>
        <span class="highlight">地主佃戶關係</span>：
        <ul>
          <li>農村社會以地主佃戶關係為主</li>
          <li>佃戶向地主租地耕種</li>
          <li>地租成為主要負擔</li>
          <li>形成地主經濟格局</li>
        </ul>
      </li>
      <li>
        <span class="highlight">國家政策調整</span>：
        <ul>
          <li>國家不再主動重新分配土地</li>
          <li>從稅制與財政着手調整</li>
          <li>透過田賦調節社會關係</li>
          <li>承認地主經濟現實</li>
        </ul>
      </li>
      <li>
        <span class="highlight">財政結構多元化</span>：
        <ul>
          <li>田稅不再是唯一財政支柱</li>
          <li>商稅、酒稅、茶鹽專賣成為重要來源</li>
          <li>商業稅收比例增加</li>
          <li>財政結構多元化</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（二）對農村社會的影響</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">宗族村落與地方權力中心</span>：
        <ul>
          <li>地主經濟使鄉村社會形成宗族村落與地方權力中心</li>
          <li>地主掌握地方實權</li>
          <li>形成地方勢力</li>
          <li>對中央統治既有依賴也有制衡</li>
        </ul>
      </li>
      <li>
        <span class="highlight">農民處境</span>：
        <ul>
          <li>農民失去土地</li>
          <li>成為佃戶或流民</li>
          <li>地租負擔沉重</li>
          <li>生活困難</li>
        </ul>
      </li>
      <li>
        <span class="highlight">社會矛盾</span>：
        <ul>
          <li>貧富差距擴大</li>
          <li>社會矛盾激化</li>
          <li>農民起義不斷</li>
          <li>統治不穩</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（三）對國家政權的影響</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">重文輕武</span>：
        <ul>
          <li>宋代重文輕武</li>
          <li>傾向透過稅收與法律管理土地與人民</li>
          <li>而非大規模田制改革</li>
          <li>維持現狀</li>
        </ul>
      </li>
      <li>
        <span class="highlight">田制較少劇烈變動</span>：
        <ul>
          <li>在整體上，田制較少劇烈變動</li>
          <li>有利於經濟與社會穩定</li>
          <li>但難以根治貧富差距與流民問題</li>
          <li>社會問題依然存在</li>
        </ul>
      </li>
      <li>
        <span class="highlight">財政結構變化</span>：
        <ul>
          <li>財政結構多元化</li>
          <li>商業稅收成為重要來源</li>
          <li>減少對農業稅收的依賴</li>
          <li>促進商業發展</li>
        </ul>
      </li>
    </ul>

