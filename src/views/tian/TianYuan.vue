        <ul>
          <li>不平等的土地與賦稅制度</li>
          <li>加深民族與階級矛盾</li>
          <li>引發多次民變</li>
          <li>為元末起義埋下伏線</li>
        </ul>
      </li>
      <li>
        <span class="highlight">社會動盪</span>：
        <ul>
          <li>族群差別政策對後世民族關係與土地問題產生長遠影響</li>
          <li>影響社會穩定</li>
          <li>引發反抗運動</li>
          <li>最終導致元朝滅亡</li>
        </ul>
      </li>
    </ul>

