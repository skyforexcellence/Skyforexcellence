          <li>土地品質較差</li>
          <li>賦役負擔沉重</li>
          <li>生活困難</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（二）族群矛盾的影響</h3>
    <ul class="section-list">
      <li>
