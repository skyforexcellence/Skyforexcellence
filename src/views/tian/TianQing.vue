    <h2 class="section-title">
      十、清代田制的歷史總結
    </h2>
    <p class="section-text">
      清代田制是明清地主經濟發展到高峰時的調整階段，其特點包括︰
    </p>
    <ul class="section-list">
      <li>
        <span class="highlight">延續結構：</span>在不觸動地主佃戶結構的前提下，延續明代的土地結構，承認既有土地私有關係。
      </li>
      <li>
        <span class="highlight">稅制改革：</span>透過地丁合一與稅制改革來改善賦稅分配，廢除兩千多年的人頭稅。
      </li>
      <li>
        <span class="highlight">人口爆炸：</span>在稅制改革和高產作物引進的背景下，人口爆炸增長，兩百餘年間從約1億增至4億。
      </li>
      <li>
        <span class="highlight">人口壓力：</span>在人口劇增與土地集中條件下，即使名義上減輕人頭稅，農民實際負擔仍然沉重。
      </li>
      <li>
        <span class="highlight">過渡角色：</span>清代田制在長期歷史中起到過渡角色，為近代的土地改革奠定基礎。
      </li>
    </ul>

