      </li>
      <li>
        隱瞞人丁的現象嚴重，國家稅收減少。
      </li>
      <li>
        康熙帝認為「見在人丁加徵錢糧，實有不可」，因為「人丁雖增、地畝並未加廣」。
      </li>
    </ul>

