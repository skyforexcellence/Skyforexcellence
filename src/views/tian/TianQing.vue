      （三）政策意義
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">鼓勵人口增長：</span>新增人口不再徵稅，有利於人口恢復與家庭增產，提高勞動力。
      </li>
      <li>
        <span class="highlight">減輕人民負擔：</span>在一定程度上減輕了人民的人頭稅負擔。
      </li>
      <li>
        <span class="highlight">經濟意義：</span>是中國封建社會徭役向賦稅轉化的重要標誌。
      </li>
      <li>
        <span class="highlight">歷史影響：</span>為後來的「攤丁入畝」奠定了基礎。
      </li>
    </ul>

    <h3 class="subsection-title">
      （四）政策問題
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">新增不稅，舊額不減：</span>新增人丁不徵稅，但舊額人丁的稅額不減少。
      </li>
      <li>
        <span class="highlight">抵補問題：</span>新增人丁很多，用誰來補充舊丁缺額，很難做到苦樂平均。
      </li>
      <li>
        <span class="highlight">負擔不均：</span>人均負擔可能隨人口增長而攤薄或加重，視土地多少而定。
      </li>
      <li>
        <span class="highlight">需要進一步改革：</span>出現矛盾，需要推行「攤丁入畝」來解決。
      </li>
    </ul>

    <h2 class="section-title">
      六、地丁合一與攤丁入畝
    </h2>
    <p class="section-text">
      「地丁合一」和「攤丁入畝」是清朝中期的重大稅制改革，是漢唐以來長期實行的人頭稅廢除的標誌。
    </p>

    <h3 class="subsection-title">
      （一）政策背景
    </h3>
    <ul class="section-list">
      <li>
        「滋生人丁永不加賦」後出現矛盾，需要進一步改革。
      </li>
      <li>
        人頭稅（丁稅）成為人民沉重負擔，阻礙社會發展。
      </li>
      <li>
        土地兼併嚴重，無地少地農民無力承擔丁稅。
      </li>
      <li>
        需要簡化稅制，減輕人民負擔，促進社會經濟發展。
      </li>
    </ul>

