    <h3 class="subsection-title">
      （一）背景內容
    </h3>
    <ul class="exam-points">
      <li>
        <strong>背景：</strong>清朝建立後，延續明代地主佃戶格局，承認既有土地私有關係。入關後的戰亂和社會動盪需要恢復經濟。
      </li>
      <li>
        <strong>時間：</strong>清朝（1644-1911年），主要改革時期為康熙五十年（1712年）至雍正二年（1724年）。
      </li>
      <li>
        <strong>延續：</strong>清朝大致延續明末地主佃戶格局，承認既有土地私有關係，部分官員與八旗貴族獲封旗地與莊田。
      </li>
    </ul>

    <h3 class="subsection-title">
      （二）主要措施
    </h3>
    <ul class="exam-points">
      <li>
        <strong>滋生人丁永不加賦：</strong>康熙五十一年（1712年）頒布，以康熙五十年的人丁數為固定丁數，此後新增人口不再額外加徵人頭稅。
      </li>
      <li>
        <strong>地丁合一：</strong>清中期實行，把原本分開的地稅與丁稅合併，逐步取消對成年男子獨立徵收的人頭稅。
      </li>
      <li>
        <strong>攤丁入畝：</strong>把原丁稅平均攤入田稅之中，按田地面積徵收，在形式上減輕了無田或少田人口的直接負擔。
      </li>
      <li>
        <strong>實施時間：</strong>康熙五十五年（1716年）在廣東、四川試行，雍正二年（1724年）開始在全國推廣，逐漸完成稅制改革。
