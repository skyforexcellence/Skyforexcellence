          <li>官員對土地兼併視而不見</li>
          <li>甚至與豪強勾結，兼併土地</li>
          <li>難以有效限制土地兼併</li>
        </ul>
      </li>
      <li>
        <span class="highlight">繼承制度</span>：
        <ul>
          <li>土地繼承制度導致土地細分</li>
          <li>家庭子女增多，土地面積減小</li>
          <li>小農經濟規模縮小</li>
          <li>更容易破產失去土地</li>
        </ul>
      </li>
    </ul>

