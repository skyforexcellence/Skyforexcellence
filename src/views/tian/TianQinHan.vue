        </ul>
      </li>
      <li>
        <span class="highlight">地主免役、逃稅</span>：
        <ul>
          <li>地主利用特權免役、逃稅</li>
          <li>小農稅負沉重，生活困苦</li>
          <li>農民願意依附地主</li>
          <li>形成「客戶」關係，保護農民</li>
        </ul>
      </li>
      <li>
        <span class="highlight">地方官吏與豪強勾結</span>：
        <ul>
