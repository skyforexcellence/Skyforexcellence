              <li>地主階級的土地並不屬於均田範圍</li>
              <li>豪族大地主的土地未受影響</li>
              <li>貴族、官僚、寺院仍擁有大量土地</li>
              <li>土地兼併仍在繼續</li>
            </ul>
          </li>
          <li>
            <span class="highlight">奴婢受田的問題</span>：
            <ul>
              <li>奴婢受田人數不限,土地歸主人</li>
              <li>有利於豪族和地主</li>
              <li>導致土地繼續集中</li>
              <li>違背了均田的初衷</li>
            </ul>
          </li>
          <li>
            <span class="highlight">執行困難</span>：
            <ul>
              <li>均田制在各地執行不平衡</li>
              <li>有些地區土地不足</li>
              <li>有些地區農民無法獲得足夠土地</li>
              <li>制度效果打折扣</li>
            </ul>
          </li>
          <li>
            <span class="highlight">地方勢力反對</span>：
            <ul>
              <li>地方豪族對改革不滿</li>
              <li>部分貴族反對漢化</li>
              <li>甚至發生叛亂</li>
              <li>影響制度的實施</li>
            </ul>
          </li>
        </ul>
      </div>
    </div>

    <h2 class="subsection-title">
      六、均田制瓦解的原因
    </h2>
    <h3 class="section-title">（一）土地兼併繼續發展</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">豪族地主兼併</span>：
        <ul>
          <li>豪族地主利用特權繼續兼併土地</li>
          <li>通過買賣、強奪等方式獲得土地</li>
          <li>小農失去土地,成為佃戶</li>
          <li>土地集中現象繼續發展</li>
        </ul>
      </li>
      <li>
        <span class="highlight">寺院莊園興起</span>：
        <ul>
          <li>寺院利用宗教特權兼併土地</li>
          <li>獲得大量莊田</li>
          <li>寺院經濟興起</li>
          <li>與貴族莊園競爭</li>
        </ul>
      </li>
      <li>
        <span class="highlight">莊園經濟發展</span>：
        <ul>
          <li>莊園主擁有大量土地</li>
          <li>雇用佃戶耕種</li>
          <li>莊園內自給自足</li>
          <li>不受國家直接管理</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（二）人口增加與土地不足</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">人口增加</span>：
        <ul>
          <li>社會穩定,人口增加</li>
          <li>受田農民增加</li>
          <li>土地需求增加</li>
          <li>可分配的無主荒地減少</li>
        </ul>
      </li>
      <li>
        <span class="highlight">土地不足</span>：
        <ul>
          <li>許多地區無法按規定分配土地</li>
          <li>部分農民無法獲得足夠土地</li>
          <li>均田制難以繼續實行</li>
          <li>制度效果下降</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（三）政治動盪與執行不力</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">政治動盪</span>：
        <ul>
          <li>北魏後期政治動盪</li>
          <li>統治階級內部鬥爭</li>
          <li>地方勢力坐大</li>
          <li>中央控制力下降</li>
        </ul>
      </li>
      <li>
        <span class="highlight">執行不力</span>：
        <ul>
          <li>均田制執行愈來愈困難</li>
          <li>地方官員缺乏動力執行</li>
          <li>戶籍與田籍失實</li>
          <li>制度逐漸走樣</li>
        </ul>
      </li>
      <li>
        <span class="highlight">制度變通</span>：
        <ul>
          <li>東魏、西魏、北齊、北周在原有基礎上作出各自變通</li>
          <li>制度逐漸走樣</li>
          <li>失去原有的精神</li>
          <li>直至隋朝重新整理</li>
        </ul>
      </li>
    </ul>

    <h2 class="subsection-title">
      七、北魏田制的歷史意義
    </h2>
    <h3 class="section-title">（一）制度創新</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">首次全國範圍國家分田</span>：
        <ul>
          <li>首次在全國範圍內以國家名義重新分配土地</li>
          <li>而非完全依賴貴族與地主</li>
          <li>建立國家直接管理的農民階層</li>
          <li>是中國田制史上的重大創新</li>
        </ul>
      </li>
      <li>
        <span class="highlight">土地國有制的嘗試</span>：
        <ul>
          <li>建立土地國有制</li>
          <li>國家擁有土地分配權和收回權</li>
          <li>農民獲得使用權和部分所有權</li>
          <li>有利於土地資源的合理分配</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（二）對後世的影響</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">隋唐均田制的直接基礎</span>：
        <ul>
          <li>提供了隋唐均田制設計的直接經驗</li>
          <li>包括按人口授田的概念</li>
          <li>包括口分田與永業田的區分</li>
          <li>隋唐均田制直接繼承北魏均田制</li>
        </ul>
      </li>
      <li>
        <span class="highlight">影響東亞地區</span>：
        <ul>
          <li>北魏均田制在東亞地區出現</li>
          <li>對這些地區土地制度產生深遠影響</li>
          <li>成為東亞田制的重要參考</li>
          <li>影響朝鮮、日本等國</li>
        </ul>
      </li>
      <li>
        <span class="highlight">中國田制發展的重要里程碑</span>：
        <ul>
          <li>標誌著中國田制從「限制豪族」走向「全面國家分田」</li>
          <li>是中國田制發展的重要里程碑</li>
          <li>影響後世田制改革</li>
          <li>為後世提供重要參考</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（三）北魏統治的鞏固</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">促進經濟恢復</span>：
        <ul>
          <li>恢復戰後農業生產</li>
          <li>開墾大量荒地</li>
          <li>農業產量增加</li>
          <li>經濟逐漸繁榮</li>
        </ul>
      </li>
      <li>
        <span class="highlight">穩定社會秩序</span>：
        <ul>
          <li>農民生活穩定</li>
          <li>流民減少</li>
          <li>社會秩序改善</li>
          <li>減少農民起義</li>
        </ul>
      </li>
      <li>
        <span class="highlight">加強中央集權</span>：
        <ul>
          <li>打破豪族控制</li>
          <li>加強國家對人民的控制</li>
          <li>鞏固北魏統治</li>
          <li>推動北魏進入鼎盛時期</li>
        </ul>
      </li>
      <li>
        <span class="highlight">推動漢化改革</span>：
        <ul>
          <li>均田制是漢化改革的一部分</li>
          <li>促進鮮卑族漢化</li>
          <li>促進民族融合</li>
          <li>推動北魏社會發展</li>
        </ul>
      </li>
    </ul>

