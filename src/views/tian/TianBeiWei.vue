          <li>不同於地主土地私有制</li>
        </ul>
      </li>
      <li>
        <span class="highlight">限期使用</span>：
        <ul>
          <li>露田、麻田屬「限期使用」性質</li>
          <li>死亡或戶口變動時須歸還官府</li>
          <li>由國家再分配給其他人</li>
          <li>保證土地循環利用</li>
        </ul>
      </li>
      <li>
        <span class="highlight">永業田</span>：
        <ul>
          <li>桑田為永業田,可世襲繼承</li>
          <li>保障家庭基本生計</li>
          <li>增強農民留在土地上的意願</li>
          <li>提高農民生產積極性</li>
        </ul>
      </li>
      <li>
        <span class="highlight">限制買賣</span>：
        <ul>
          <li>露田不準買賣</li>
          <li>桑田可限製買賣</li>
          <li>防止土地再次兼併</li>
          <li>維護均田制的實施</li>
