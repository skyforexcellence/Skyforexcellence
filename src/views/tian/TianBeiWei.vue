          <li>受田農民向國家繳納租稅</li>
          <li>承擔一定的徭役和兵役</li>
          <li>保證國家賦役來源</li>
        </ul>
      </li>
      <li>
        <span class="highlight">改善財政</span>：
        <ul>
          <li>增加國家收入</li>
          <li>穩定稅源</li>
          <li>支持國家行政與軍事</li>
          <li>加強國家統治能力</li>
        </ul>
      </li>
    </ul>

