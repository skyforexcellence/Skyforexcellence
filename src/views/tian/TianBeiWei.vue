    <h3 class="section-title">（三）土地的性質與權責</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">土地國有制</span>：
        <ul>
          <li>均田制下的土地為國家所有</li>
          <li>國家擁有土地的分配權和收回權</li>
