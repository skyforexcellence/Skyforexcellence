    <h2 class="subsection-title">
      三、屯田制︰曹操的創新
    </h2>
    <h3 class="section-title">（一）基本做法</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">軍屯</span>：
        <ul>
          <li>由軍隊主持開墾荒地</li>
          <li>士兵在戰時作戰，閒時耕種</li>
          <li>收成主要歸官府，用作軍糧</li>
          <li>減輕軍隊對民間糧食的依賴</li>
        </ul>
      </li>
      <li>
        <span class="highlight">民屯</span>：
        <ul>
          <li>由官府組織流民耕種</li>
          <li>官府提供耕牛、農具、種子</li>
          <li>收成與官府分成</li>
          <li>流民獲得生活保障</li>
        </ul>
      </li>
      <li>
        <span class="highlight">管理方式</span>：
        <ul>
          <li>設立屯田官，專門管理</li>
          <li>建立屯田區，與普通農田分開</li>
          <li>屯田戶有專門戶籍</li>
          <li>不得自由遷徙</li>
        </ul>
      </li>
    </ul>

