          <li>有助長期用兵</li>
          <li>減輕百姓負擔</li>
          <li>支持曹操統一北方</li>
        </ul>
      </li>
      <li>
        <span class="highlight">吸收流民</span>：
        <ul>
          <li>吸收大量流民</li>
          <li>避免他們成為動亂力量</li>
          <li>穩定社會秩序</li>
          <li>恢復農業生產</li>
        </ul>
      </li>
