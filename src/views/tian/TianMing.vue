        </ul>
      </li>
      <li>
        <span class="highlight">里甲制</span>：
        <ul>
          <li>設立里甲制，以十戶為甲、十甲為里</li>
          <li>方便徵稅與徭役分配</li>
          <li>建立基層組織</li>
          <li>強化國家控制</li>
        </ul>
      </li>
      <li>
        <span class="highlight">戶籍分類</span>：
        <ul>
          <li>把居民分為軍戶、民戶、匠戶等不同身分</li>
          <li>各自承擔田賦與勞役責任</li>
          <li>職業世襲</li>
