          <li>讓軍戶與一般百姓在指定地區耕作</li>
          <li>以供應軍糧與公糧</li>
          <li>增加糧食產量</li>
        </ul>
      </li>
      <li>
        <span class="highlight">恢復經濟</span>：
        <ul>
          <li>這些措施在明初有助於迅速恢復戰後凋敝的農村經濟</li>
          <li>開墾大量荒地</li>
          <li>增加糧食產量</li>
          <li>改善國家財政</li>
        </ul>
      </li>
    </ul>

