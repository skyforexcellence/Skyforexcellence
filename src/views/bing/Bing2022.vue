            <h3 class="answer-subtitle">(b) 題作答</h3>
            <div class="answer-content">
              <p>唐代府兵制與明代衛所制，本質上都是以土地分配為核心的「寓兵於農」軍事制度，兩者最終都走向崩潰、導致王朝國勢由盛轉衰，核心原因完全一致：一是制度賴以生存的土地基礎被瓦解，二是士兵的社會地位持續低落，最終讓整個軍事體系徹底失效，引發了一連串的政治、經濟危機。以下將從指定的兩個方面，分別闡析兩朝制度崩壞的歷程與影響。</p>

              <p>首先是土地分配不足的問題，這是兩套制度崩潰的根本原因。不論是唐代的府兵制，還是明代的衛所制，核心邏輯都是「國家給士兵授田，士兵用服役換取土地的使用權」，一旦土地分配無法兌現，這套制度就失去了存在的根基。</p>

              <p>先看唐代的情況。唐代府兵制的基礎是均田制，唐初戰亂之後，全國有大量無主荒地，國家有足夠的土地給府兵授田。但從唐高宗、武則天時期開始，土地兼併愈演愈烈，貴族、官僚、富商大肆霸佔百姓的土地，國家手中掌握的荒地越來越少，根本無法繼續按規定給府兵授田。武則天在位時，關中地區很多丁男，能拿到的授田連規定數額的一半都不到，甚至有不少府兵徹底失去了土地。沒有了土地，府兵就沒有了收入來源，根本無力自備糧食、武器去服役，只能紛紛逃亡。到了唐玄宗開元年間，全國的折衝府已經交不出足夠的府兵去京城宿衛，史書記載為「府兵耗散，番上不至」，府兵制已經名存實亡。最終唐玄宗只能廢除府兵制，改行募兵制。而募兵制是國家花錢養兵，軍費開支暴增，給國家財政造成了沉重負擔；更嚴重的是，邊防的募兵都掌握在節度使手中，形成了「外重內輕」的局面，最終爆發了安史之亂，唐朝的國勢從此由盛轉衰，再也無法恢復往日的輝煌。</p>

              <p>再看明代的衛所制，幾乎重複了唐代的悲劇。明代衛所制的核心是「軍屯制度」，國家給每個世襲軍戶分配五十畝屯田，士兵平時耕種屯田，收穫的糧食養活自己與衛所衛所軍官，戰時出征，朱元璋曾誇口說「養兵百萬，不費百姓一粒米」。但從明宣宗、明英宗時期開始，王公，王公貴族、衛所軍官就開始大肆侵吞軍屯土地，把國家的屯田變成自己的私田，還把軍戶變成自己的佃農，國家掌握的軍屯數量急劇減少。正統年間的統計顯示，全國超過一半的軍屯土地已經被侵吞，大量軍戶失去了屯田，沒有了收入，只能紛紛逃亡，衛所的兵源越來越少，戰鬥力也直線下降。到了明朝中後期，衛所制已經名存實亡，國家只能靠募兵來對付倭寇、蒙古與後金，比如戚繼光的戚家軍，就是完全招募來的軍隊。募兵需要巨額的軍費，明朝中後期內憂外患不斷，軍費開支越來越大，國家只能不斷加徵稅收，也就是後來的「遼餉、剿餉、練餉」三餉，進一步激化了社會矛盾，引發了大規模的農民起義，最終導致明朝滅亡，國勢徹底走向衰敗。</p>

              <p>其次是士兵地位低落的問題，這是兩套制度無法維持的重要推手。一套軍事制度想要長久運行，必須讓士兵有榮譽感、有上升的通道，一旦士兵被社會看不起，被隨意欺辱，就沒有人願意為國家賣命，制度自然就崩潰了。</p>

              <p>先看唐代府兵的地位變化。唐初的府兵，社會地位極高，因為府兵都來自富室強丁，有田有地，立下戰功就能獲得勳官爵位，甚至能入朝為官，當時的人都以當府兵為榮。但從唐高宗時期開始，府兵的地位一落千丈：朝廷與權貴隨意役使府兵，讓他們給自己修宅子、種地、當雜役，就對待奴僕一樣，根本不把他們當軍人看待；府兵立下戰功得不到獎賞，戰死沙場也沒有人過問，甚至連基本的撫恤都沒有。與此同時，科舉制越來越完善，社會上重文輕武的風氣越來越濃，武人被文人看不起，大家都不願意當府兵，紛紛逃避兵役，甚至不惜殘疾自己的身體來逃役。府兵的素質也越來越差，原來是富室強丁，後來只能找貧弱農戶甚至流民來充數，戰鬥力直線下降。府兵制崩潰後，唐朝改行募兵制，招募的士兵大多是市井無賴、流民，沒有受過系統訓練，戰鬥力極低，邊防大權都落在節度使手中，最終釀成安史之亂，唐朝的盛世從此一去不返。</p>

              <p>再看明代衛所士兵的地位，比唐代府兵更為悲慘。明代衛所的士兵是世襲軍戶，一輩子都被束縛在衛所裡，子子孫孫都要當兵，根本沒有選擇的餘地。從明朝中期開始，衛所軍官隨意役使士兵、剋扣糧餉，把士兵當成自己的奴僕，士兵連基本溫飽都無法保證。更嚴重的是，明朝有「以罪充軍」的制度，把犯了罪的人發配到衛所當兵，時間長了，整個社會都把當兵看成是一種懲罰，是低賤的職業，軍戶的子弟甚至不能參加科舉考試，完全沒有上升的通道。在這樣的情況下，根本沒有人願意當衛所兵，軍戶紛紛逃亡，衛所的兵源與戰鬥力都徹底崩潰。明英宗時期的土木堡之變，五十萬明軍被瓦剌兩萬軍隊打敗，連皇帝都被活捉，核心原因就是衛所的士兵長期缺乏訓練、士氣低落，根本不堪一擊。明朝中後期，衛所制完全失效，國家只能靠募兵維持，沉重的軍費拖垮了國家財政，面對後金的進攻與農民起義，根本無力抵擋，最終走向了滅亡。</p>

              <p>總而言之，唐代府兵制與明代衛所制的崩潰，本質上都是土地兼併摧毀了制度的根基，士兵地位低落擊垮了制度的運行動力。兩朝在制度崩潰後改行的募兵制，不僅給國家造成了無法承受的財政負擔，更引發了軍權旁落、社會動盪等一連串危機，最終導致王朝國勢由盛轉衰。這也告訴我們，一套穩定的軍事制度，從來不只是單純的軍事問題，更是與土地制度、社會階層、國家治理深度綁定的核心國策，一旦根基動搖，整個王朝的命運都會隨之改變。</p>
            </div>
          </div>
