            <h3 class="answer-subtitle">(b) 題作答</h3>
            <div class="answer-content">
              <p>明代衛所制是明太祖朱元璋為鞏固統治、杜絕軍閥割據而創立的核心軍事制度，曾為明初的穩定與邊防鞏固立下汗馬功勞，但從明宣宗、明英宗時期開始，這套制度就逐步走向廢弛，到明朝中後期已經名存實亡。究其根本，衛所制的廢弛並非單一因素導致，而是制度先天缺陷、政治腐敗侵蝕、社會經濟變化共同作用的結果，以下將結合史料與史實展開析論。</p>

              <p>首先，軍權被上層剝奪、制度運行體系崩潰，是衛所制廢弛的核心政治原因。明太祖朱元璋設計衛所制時，嚴格規定「兵將分離、軍權歸於中央」，兵部掌握調遣權，五軍都督府掌握軍隊管理權，兩者互相制衡，確保軍權牢牢掌握在皇帝手中。但從明成祖之後，這套制衡體系就逐步被打破：皇帝越來越信任宦官，經常派宦官擔任監軍、提督京營，甚至讓宦官總督軍務，比如正統年間的宦官王振、正德年間的劉瑾、天啟年間的魏忠賢，都曾全面掌控軍隊大權，原本負責軍務的兵部、五軍都督府被架空，衛所制的運行規則被完全打亂。宦官與朝中權貴不僅隨意干預衛所的軍務，更把衛所士兵當成自己的私人奴僕，隨意調遣士兵給自己修宅子、種地、辦私事，衛所原本的訓練、屯田、戍守職能被完全忽視。就連負責守衛京師的京營，都被宦官與權貴把持，士兵淪為雜役，根本沒有時間接受軍事訓練，戰鬥力直線下降。當衛所制的核心運行規則被政治腐敗完全破壞，這套制度自然就只能走向廢弛。</p>

              <p>其次，衛所士兵生活極度困苦、大量逃亡，是衛所制廢弛的直接原因。衛所制的生存根基是軍屯制度，國家給每個軍戶分配五十畝屯田，讓士兵靠屯田收穫自給自足。但從明朝中期開始，王公貴族、衛所軍官就開始大肆侵吞軍屯土地，他們把國家分配給軍戶的屯田變成自己的私人莊園，還把軍戶變成自己的佃農，強迫他們給自己耕種。根據正統年間的官方統計，當時全國超過一半的軍屯土地已經被權貴與軍官侵吞，大量軍戶失去了賴以生存的屯田，卻依然要向衛所繳納定額的糧稅，連基本的溫飽都無法保證。更糟糕的是，衛所軍官還經常層層剋扣士兵的糧餉，隨意役使士兵服各種雜役，甚至虐待士兵致死，士兵的處境與奴隸無異。在這樣的處境下，軍戶只能紛紛選擇逃亡，脫離衛所的控制。根據史料記載，到正統年間，全國衛所逃亡的士兵數量已經達到總兵額的一半以上，很多衛所只剩空殼，連基本的兵額都湊不齊。士兵大量逃亡，衛所制就失去了最核心的主體，自然只能逐步廢弛。</p>

              <p>最後，衛所軍隊戰鬥力全面崩潰，無法應對明朝的內憂外患，朝廷被迫改行募兵制，是衛所制廢弛的根本軍事原因。衛所制實行終身世襲的軍戶制度，士兵從出生就註定要當兵，就算年老體弱、殘疾無力，也無法脫離軍籍，導致衛所軍隊裡充斥著大量老弱病殘，士兵素質本就參差不齊。加上軍屯被侵吞、士兵被隨意役使，衛所士兵根本沒有時間、也沒有心思接受軍事訓練，訓練完全廢弛，戰鬥力一落千丈。明英宗正統年間的土木堡之變，就是衛所制戰鬥力崩潰的最直接體現：五十萬京營的衛所軍隊，被瓦剌兩萬騎兵打得全軍覆沒，連明英宗本人都被活捉，這場慘敗讓明朝朝廷徹底意識到，衛所兵已經不堪一用。此後，明朝面臨的內憂外患越來越嚴重：東南沿海有倭寇不斷侵擾，北方有蒙古部落頻繁入侵，後期還有後金政權的威脅，國內還有接連不斷的農民起義，而衛所兵根本無法應對這些危機。朝廷只能依靠募兵來應對戰事，比如戚繼光為了對付倭寇，在浙江招募農民與礦工，組建了戰鬥力極強的戚家軍；李成梁在遼東招募士兵，組建了遼東鐵騎，這些募兵制下的職業軍隊，逐步取代了衛所軍隊，成為明朝的主力軍隊。當衛所制失去了最基本的軍事功能，無法再承擔保家衛國的職責，這套制度就只能徹底走向廢弛，最終隨著明朝的滅亡退出了歷史舞台。</p>

              <p>總而言之，明代衛所制的廢弛，是制度先天缺陷與後天政治腐敗共同作用的必然結果。政治腐敗剝奪了衛所制的運行基礎，士兵的困苦逃亡掏空了衛所制的主體，戰鬥力的崩潰讓衛所制失去了存在的意義，這套曾經輝煌的軍事制度，最終只能一步步走向廢弛，成為明朝由盛轉衰的重要見證。</p>
