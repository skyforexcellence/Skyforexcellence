    <h2 class="section-title">
      九、DSE中史考試常見題型與答題要點
    </h2>
    <h3 class="subsection-title">
      題型一：評價清朝八旗制度
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">答題要點</span>︰
        <ul class="section-list">
          <li>
            <strong>早期優點</strong>︰
            <ul class="section-list">
              <li>騎射技術領先，戰鬥力強。</li>
              <li>紀律嚴明，指揮統一。</li>
              <li>拱衛京師，鞏固統治。</li>
              <li>入關戰爭和平定三藩之亂發揮重要作用。</li>
            </ul>
          </li>
          <li>
            <strong>後期缺點</strong>︰
            <ul class="section-list">
              <li>養尊處優，缺乏訓練。</li>
              <li>長期和平，缺乏實戰經驗。</li>
              <li>人口增長，旗地不足以維持生計。</li>
              <li>難以應付近代戰爭。</li>
            </ul>
          </li>
          <li>
            <strong>總評</strong>︰八旗制度在早期有效維持統治，但後期因養尊處優和缺乏訓練而衰落，無法應付近代戰爭。
          </li>
        </ul>
      </li>
    </ul>

    <h3 class="subsection-title">
      題型二：分析清朝兵制的演變及其原因
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">答題要點</span>︰
        <ul class="section-list">
          <li>
            <strong>演變過程</strong>︰
            <ul class="section-list">
              <li>清初（1644-18世紀中葉）︰八旗、綠營並行。</li>
              <li>19世紀中葉︰八旗、綠營衰落，湘軍、淮軍興起。</li>
              <li>19世紀末︰新軍建立，成為主力。</li>
            </ul>
          </li>
          <li>
            <strong>演變原因</strong>︰
            <ul class="section-list">
              <li>八旗、綠營戰鬥力下降，無法應付戰爭。</li>
              <li>太平天國、捻軍等內亂，需要新軍隊鎮壓。</li>
              <li>甲午戰敗，需要近代化軍隊。</li>
              <li>自強運動推動軍事近代化。</li>
            </ul>
          </li>
          <li>
            <strong>影響</strong>︰
            <ul class="section-list">
              <li>軍權下放，形成軍閥割據。</li>
              <li>新軍推翻清朝，建立中華民國。</li>
            </ul>
          </li>
        </ul>
      </li>
    </ul>

