    <h2 class="section-title">
      十、DSE中史考試常見題型與答題要點
    </h2>
    <h3 class="subsection-title">
      題型一：分析明朝兵制的演變及原因
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">答題要點</span>︰
        <ul class="section-list">
          <li>
            <strong>時期劃分</strong>︰前期（洪武至正統初）以衛所制為主；中後期（正統至明末）以營伍制和募兵制為主。
          </li>
          <li>
            <strong>演變原因</strong>︰
            <ul class="section-list">
              <li>軍戶大規模逃亡，衛所兵源枯竭</li>
              <li>軍屯田地被侵占，經濟基礎瓦解</li>
              <li>土木堡之變，衛所制軍事威信受損</li>
              <li>邊患和內亂頻仍，需要戰鬥力更強的部隊</li>
              <li>武器裝備進步（如火器），需要職業化訓練</li>
            </ul>
          </li>
          <li>
            <strong>影響</strong>︰軍隊戰鬥力提升，但軍費負擔加重，成為明朝滅亡的重要原因之一。
          </li>
        </ul>
      </li>
    </ul>

    <h3 class="subsection-title">
      題型二：評價明朝衛所制
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">答題要點</span>︰
        <ul class="section-list">
          <li>
            <strong>優點</strong>︰
            <ul class="section-list">
              <li>實現軍費自給，不增加百姓負擔</li>
              <li>兵源>兵源穩定，戰時可快速徵調</li>
              <li>兵將分離，避免武將割據</li>
              <li>軍權集中於皇帝，有利於中央集權</li>
            </ul>
          </li>
          <li>
            <strong>缺點</strong>︰
            <ul class="section-list">
              <li>軍戶世襲負擔過重，逃亡嚴重</li>
              <li>軍屯田地被侵占，經濟基礎瓦解</li>
              <li>兵將不識，戰鬥力低下</li>
              <li>制度過於剛性，難以適應社會變化</li>
            </ul>
          </li>
          <li>
            <strong>總評</strong>︰明初有效，中期後崩壞；其興衰反映了世襲兵制的局限性。
          </li>
        </ul>
      </li>
    </ul>

    <h3 class="subsection-title">
      題型三：分析明朝軍費問題與明朝滅亡的關係
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">答題要點</span>︰
        <ul class="section-list">
          <li>
            <strong>軍費增加原因</strong>︰
            <ul class="section-list">
              <li>衛所制崩壞，轉向募兵制，軍費由朝廷承擔</li>
              <li>九邊重鎮龐大軍費，佔全國歲入40-50%</li>
              <li>遼東戰事頻繁，需要大量軍費</li>
              <li>農民起義，需要剿餉</li>
            </ul>
          </li>
          <li>
            <strong>軍費解決方式</strong>︰加征遼餉、剿餉、練餉三餉。
          </li>
          <li>
            <strong>影響</strong>︰
            <ul class="section-list">
              <li>百姓負擔加重，激化階級矛盾</li>
              <li>經濟凋敝，國力衰退</li>
              <li>引發更多農民起義，加速明朝滅亡</li>
            </ul>
          </li>
        </ul>
      </li>
    </ul>

    <h3 class="subsection-title">
      題型四：比較明朝與前代兵制的異同
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">與唐代府兵制比較</span>︰
        <ul class="section-list">
          <li><strong>相同點</strong>︰兵農合一，自給自足。</li>
          <li><strong>不同點</strong>︰唐代府兵為民籍，明朝軍戶為軍籍；唐代府兵兵將相識，明朝衛所兵將分離。</li>
        </ul>
      </li>
      <li>
        <span class="highlight">與宋代募兵制比較</span>︰
        <ul class="section-list">
          <li><strong>相同點</strong>︰皆為職業兵，軍費由朝廷承擔。</li>
          <li><strong>不同點</strong>︰宋代募兵制為常態，明朝募兵制為衛所制崩壞後的補充。</li>
        </ul>
      </li>
    </ul>

    <h3 class="subsection-title">
      題型五：評價戚繼光的軍事改革
    </h3>
    <ul class="section-list">
      <li>
        <span class="highlight">答題要點</span>︰
        <ul class="section-list">
          <li>
            <strong>改革內容</strong>︰創立鴛鴦陣、嚴格訓練、賞罰分明、招募精兵。
          </li>
          <li>
            <strong>歷史貢獻</strong>︰基本肅清東南沿海倭患，為明朝中期抗倭戰爭做出重大貢獻。
          </li>
          <li>
            <strong>啟示</strong>︰軍隊職業化、訓練專業化、武器裝備現代化是提升戰鬥力的關鍵。
          </li>
        </ul>
      </li>
    </ul>
