        <span class="highlight">遼餉、剿餉、練餉</span>
        」三餉，巨額軍費拖垮明朝財政，激化民變；同時募兵多由武將私募，形成「兵為將有」，為晚明軍閥化埋下隱患。
      </li>
      <li>
        <span class="highlight">戚繼光軍事改革</span>（重要史實）︰
