        <span class="highlight">九邊軍費</span>︰明末九邊每年軍費約
        <span class="highlight">1000-1500 萬兩</span>  白銀，佔全國歲入
        <span class="highlight">40-50%</span>  ，成為明朝財政最大負擔。
      </li>
    </ul>

    <h2 class="section-title">
      七、核心總結與歷史定位
    </h2>
    <ul class="section-list">
      <li>
        制度優點︰前期衛所制實現軍費高度自給、兵源穩定，並透過兵將分離與權力制衡，將軍權收歸中央，有效避免武將割據，支撐明初疆域擴張與政權穩定。
      </li>
      <li>
        制度缺陷︰世襲軍戶制與軍屯制過於剛性，難以適應社會變化，中期後快速崩壞；兵將分離導致衛所軍戰力低，應對邊患與內亂靈活性不足。
      </li>
      <li>
        興衰關聯︰中後期營伍制與募兵制雖提升明軍實戰力並延續統治，但無節制募兵帶來巨額軍費，引發「加征—逃亡—再征—再逃」惡性循環，成為壓垮王朝的關鍵。
      </li>
      <li>
        歷史定位︰明朝兵制是由世襲兵制向
        <span class="highlight">職業僱傭兵制</span>
        過渡的重要階段，獨立火器部隊建制開啟中國軍事近代化先聲，其制度設計與興衰教訓深刻影響清代綠營兵制。
      </li>
    </ul>

    <h2 class="section-title">
      八、重要歷史事件時間軸（DSE重點）
    </h2>
    <ul class="section-list">
      <li>
        <span class="highlight">1368年</span>︰朱元璋建立明朝，開始推行衛所制。
      </li>
      <li>
        <span class="highlight">1380年</span>︰廢中書省，廢丞相制，設五軍都督府與兵部，確立「以部制府」體制。
      </li>
      <li>
        <span class="highlight">1402-1424年</span>︰永樂年間，軍屯產量達到頂峰，基本實現全國軍費自給。
      </li>
      <li>
        <span class="highlight">1449年</span>︰土木堡之變，京營三大營精銳全軍覆沒，衛所制軍事威嚴受損。
      </li>
      <li>
        <span class="highlight">正統年間（1436-1449）</span>︰全國衛所逃亡軍士達百萬之巨，衛所兵源枯竭。
      </li>
      <li>
        <span class="highlight">嘉靖年間（1522-1566）</span>︰倭寇侵擾東南沿海，戚繼光建立戚家軍，募兵制全面推廣。
      </li>
      <li>
        <span class="highlight">1567年</span>︰戚繼光調任北方，改革九邊防務，建立車營、火器營。
      </li>
      <li>
        <span class="highlight">1592-1598年</span>︰萬曆援朝戰爭，明軍主力皆為募兵，約10-15萬人。
      </li>
      <li>
        <span class="highlight">1618-1644年</span>︰遼東戰事興起，募兵規模急劇擴大，加征遼餉、剿餉、練餉三餉。
      </li>
      <li>
        <span class="highlight">1644年</span>︰李自成攻入北京，明朝滅亡，軍費負擔和募兵問題成為重要原因。
      </li>
    </ul>

