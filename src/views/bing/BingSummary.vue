      </li>
      <li>
        <span class="highlight">秦漢</span>：打破貴族壟斷，平民可透過軍功晉升（如秦的二十等爵）
      </li>
      <li>
        <span class="highlight">魏晉南北朝</span>：軍人成為特殊階層（軍戶），地位低下，世襲當兵
      </li>
      <li>
        <span class="highlight">隋唐</span>：府兵是自耕農，兵農合一，地位較高
      </li>
      <li>
        <span class="highlight">宋</span>：募兵是職業軍人，地位一般，被視為「兵痞」
      </li>
      <li>
        <span class="highlight">元</span>：四等制，蒙古人地位最高，漢人、南人地位低
      </li>
      <li>
        <span class="highlight">明</span>：軍戶世襲，地位低下，與民戶分開
      </li>
      <li>
        <span class="highlight">清</span>：八旗人地位最高，綠營兵地位一般，湘軍、淮軍成為地方勢力
      </li>
      <li>
