      三、兵制演變的四個核心維度
    </h2>

    <h3 class="section-title">（一）兵源變化：從貴族到職業軍隊</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">先秦（1046-221 BCE）</span>：貴族軍隊，軍權由周天子與諸侯掌握
      </li>
      <li>
        <span class="highlight">秦漢（221 BCE-220 CE）</span>：全民徵兵制，15-60歲男子皆可徵召
      </li>
      <li>
        <span class="highlight">魏晉南北朝（220-589）</span>：世兵制與部曲制，軍人成為特殊階層
      </li>
      <li>
        <span class="highlight">隋唐（581-907）</span>：府兵制，兵農合一，634府40-60萬
      </li>
      <li>
        <span class="highlight">宋（960-1279）</span>：募兵制，發俸招募，80-100萬禁軍
      </li>
      <li>
        <span class="highlight">元明清（1271-1912）</span>：軍戶、衛所、八旗等世襲制度，後期募兵補充
      </li>
      <li>
        <span class="highlight">晚清（1850-1912）</span>：湘軍、淮軍、新軍，職業募兵取代世襲
      </li>
    </ul>

    <h3 class="section-title">（二）軍權控制：中央與地方的博弈</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">中央集權模式</span>：
        <ul>
          <li>秦漢徵兵制：兵權直接由皇帝掌握</li>
          <li>隋唐府兵制：府兵直屬中央，防地方割據</li>
          <li>宋募兵制：更戍制定期輪換，武將無固定部隊</li>
          <li>元明清：衛所、八旗直屬中央</li>
        </ul>
      </li>
      <li>
        <span class="highlight">地方分權模式</span>：
        <ul>
          <li>先秦：諸侯擁兵自重，周王室衰微</li>
          <li>魏晉：士族、胡族擁有私人部曲</li>
          <li>晚唐：節度使掌握地方兵權與財政</li>
          <li>晚清：地方團練（湘軍、淮軍）形成軍閥</li>
        </ul>
      </li>
      <li>
        <span class="highlight">歷史教訓</span>：軍權高度集中時政權穩定，但過度抑制武將可能降低戰鬥力；地方掌握兵權易割據，但可提高作戰靈活性。
      </li>
    </ul>

    <h3 class="section-title">（三）財政負擔：兵制與經濟的關係</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">自給自足模式</span>：
        <ul>
          <li>先秦：貴族自行供養軍隊</li>
          <li>隋唐府兵：兵農合一，士兵自有土地</li>
          <li>明衛所：軍戶屯田，89萬頃產300-400萬石糧</li>
          <li>清八旗：旗戶有旗地，自給自足</li>
        </ul>
      </li>
      <li>
        <span class="highlight">財政撥款模式</span>：
        <ul>
          <li>秦漢徵兵：中央需供養戰士與家屬</li>
          <li>宋募兵：養兵費用佔財政70-80%，80-100萬禁軍</li>
          <li>晚清湘軍、淮軍：中央與地方分攤</li>
          <li>清新軍：現代化軍隊，開支龐大</li>
        </ul>
      </li>
      <li>
        <span class="highlight">財政危機</span>：
        <ul>
          <li>宋朝：養兵太重，導致「積貧積弱」</li>
          <li>晚明：軍費浩大，加派三餉</li>
          <li>晚清：新軍、海軍開支龐大，財政入不敷出</li>
        </ul>
      </li>
    </ul>

    <h3 class="section-title">（四）兵制與田制的互動</h3>
    <ul class="section-list">
      <li>
        <span class="highlight">兵制依賴田制</span>：
        <ul>
          <li>隋唐府兵制依賴均田制：均田制崩潰，府兵制無以為繼</li>
          <li>明衛所制依賴軍田：軍田被兼併，衛所軍戶逃亡</li>
          <li>清八旗依賴旗地：旗地被轉讓，八旗子弟失去依靠</li>
        </ul>
      </li>
      <li>
        <span class="highlight">田制影響兵制</span>：
        <ul>
          <li>井田制崩潰→戰國時代大規模軍隊出現</li>
          <li>均田制推行→府兵制建立</li>
          <li>均田制崩潰→募兵制取代府兵制</li>
          <li>土地兼併→農民失去土地→兵源枯竭</li>
        </ul>
      </li>
      <li>
        <span class="highlight">流民與兵源</span>：農民失去土地成為流民，往往成為兵源（如黃巢、李自成、太平天國），也帶來社會動盪。
      </li>
    </ul>

